//! On-device widget configuration: decode the widget.v1 WidgetConfig binary
//! proto (from flash/NVS or the baked-in C array) through the micropb
//! bindings and expose the estimator-facing views.
//!
//! Firmware convention: v_widget = rotation * v_sensor + offset_m.

pub use widget_pb::widget_::v1_ as pb;

use micropb::MessageDecode;
use swarm_core::math::{Quat, Vec3};

pub const SENSOR_IMU: u32 = 1;
pub const SENSOR_MAG: u32 = 2;
pub const SENSOR_UWB: u32 = 3;
pub const SENSOR_GPS: u32 = 4;
pub const SENSOR_ALT: u32 = 5;

/// Decode a serialized WidgetConfig; no allocation (heapless containers
/// sized in swarm/proto/gen_main.rs).
pub fn decode(bytes: &[u8]) -> Result<pb::WidgetConfig, micropb::DecodeError<core::convert::Infallible>> {
    let mut config = pb::WidgetConfig::default();
    config.decode_from_bytes(bytes)?;
    Ok(config)
}

pub fn quat(q: &pb::Quatf) -> Quat {
    Quat::from_array(&[q.r#w, q.r#x, q.r#y, q.r#z]).normalized()
}

pub fn vec3(v: &pb::Vec3f) -> Vec3 {
    Vec3::new(v.r#x, v.r#y, v.r#z)
}

/// Find a sensor's extrinsic by id (SENSOR_* or custom >= 128).
pub fn sensor<'a>(
    config: &'a pb::WidgetConfig,
    id: u32,
) -> Option<&'a pb::SensorExtrinsic> {
    config
        .r#extrinsics()
        .and_then(|e| e.r#sensors.iter().find(|s| s.r#id == id))
}

/// Map a sensor-frame vector measurement (direction/rate) into the widget
/// frame: rotation only.
pub fn to_widget_dir(s: &pb::SensorExtrinsic, v: Vec3) -> Vec3 {
    match s.r#rotation() {
        Some(q) => quat(q).rotate(v),
        None => v,
    }
}

/// Map a sensor-frame position into the widget frame.
pub fn to_widget_pos(s: &pb::SensorExtrinsic, v: Vec3) -> Vec3 {
    let p = to_widget_dir(s, v);
    match s.r#offset_m() {
        Some(o) => p.add(vec3(o)),
        None => p,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use micropb::{MessageEncode, PbEncoder};

    fn golden() -> Vec<u8> {
        // Generated by //swarm/tools:example_config_binpb — the Python
        // protobuf encoding of examples/widget_v1.txtpb.
        let path = format!(
            "{}/_main/swarm/tools/examples/widget_v1.binpb",
            std::env::var("TEST_SRCDIR").unwrap()
        );
        std::fs::read(path).unwrap()
    }

    /// Cross-language conformance: the canonical Python encoding must decode
    /// through micropb and RE-ENCODE TO THE IDENTICAL BYTES — byte-parity
    /// pins presence rules and packed encoding on both sides.
    #[test]
    fn golden_roundtrips_byte_identically() {
        let bytes = golden();
        let config = decode(&bytes).unwrap();

        let ex = config.r#extrinsics().unwrap();
        assert_eq!(ex.r#widget_model.as_str(), "widget-v1");
        assert_eq!(ex.r#sensors.len(), 5);

        let imu = sensor(&config, SENSOR_IMU).unwrap();
        assert!((quat(imu.r#rotation().unwrap()).w - 1.0).abs() < 1e-6);
        assert!((vec3(imu.r#offset_m().unwrap()).x - 0.012).abs() < 1e-6);

        // mag: sensor +x maps to widget +y (90 deg about z).
        let mag = sensor(&config, SENSOR_MAG).unwrap();
        let mapped = to_widget_dir(mag, Vec3::new(1.0, 0.0, 0.0));
        assert!((mapped.y - 1.0).abs() < 1e-5, "{:?}", mapped);

        let uwb = sensor(&config, SENSOR_UWB).unwrap();
        let p = to_widget_pos(uwb, Vec3::ZERO);
        assert!((p.y - 0.021).abs() < 1e-6 && (p.z - 0.008).abs() < 1e-6);

        let intr = config.r#intrinsics().unwrap();
        let imu_i = intr.r#imu().unwrap();
        assert!(imu_i._has.r#accel_noise_density());
        assert!((imu_i.r#accel_noise_density - 0.005).abs() < 1e-7);
        assert!((vec3(imu_i.r#gyro_bias().unwrap()).y + 0.02).abs() < 1e-6);
        let mag_i = intr.r#mag().unwrap();
        assert_eq!(mag_i.r#soft_iron.len(), 9);
        assert!((mag_i.r#soft_iron[4] - 0.875).abs() < 1e-5);

        // Byte-identical re-encode.
        let mut enc = PbEncoder::new(micropb::heapless::Vec::<u8, 2048>::new());
        config.encode(&mut enc).unwrap();
        assert_eq!(enc.into_writer().as_slice(), bytes.as_slice());
    }

    #[test]
    fn rejects_garbage() {
        assert!(decode(&[0xFF, 0xFF, 0xFF, 0xFF]).is_err());
    }
}
