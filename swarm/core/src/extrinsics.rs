//! On-device parser for the WEXT sensor-extrinsics blob (see
//! swarm/tools/extrinsics.py for the authoring pipeline and layout).
//!
//! Firmware can either bake the generated C header in at build time or load
//! one of these blobs from flash/NVS at boot and parse it here. No
//! allocation; caller supplies the output buffer. Layout (little-endian):
//!
//!   magic 'WEXT' | version u16 | count u16
//!   per sensor (32 B): id u8 | flags u8 | pad u16 | quat wxyz 4*f32 | offset 3*f32
//!   crc32 (IEEE) u32 over everything before it

use crate::math::{Quat, Vec3};

pub const MAGIC: [u8; 4] = *b"WEXT";
pub const VERSION: u16 = 1;

pub const SENSOR_IMU: u8 = 1;
pub const SENSOR_MAG: u8 = 2;
pub const SENSOR_UWB: u8 = 3;
pub const SENSOR_GPS: u8 = 4;
pub const SENSOR_ALT: u8 = 5;

/// One sensor's pose in the widget frame:
/// v_widget = rotation * v_sensor + offset.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SensorExtrinsic {
    pub sensor_id: u8,
    pub rotation: Quat,
    pub offset: Vec3,
}

impl Default for SensorExtrinsic {
    fn default() -> SensorExtrinsic {
        SensorExtrinsic {
            sensor_id: 0,
            rotation: Quat::IDENTITY,
            offset: Vec3::ZERO,
        }
    }
}

impl SensorExtrinsic {
    /// Map a sensor-frame vector measurement into the widget frame
    /// (directions/rates: rotation only).
    pub fn to_widget_dir(&self, v: Vec3) -> Vec3 {
        self.rotation.rotate(v)
    }

    /// Map a sensor-frame position into the widget frame.
    pub fn to_widget_pos(&self, v: Vec3) -> Vec3 {
        self.rotation.rotate(v).add(self.offset)
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum ExtrinsicsError {
    TooShort,
    BadMagic,
    BadVersion,
    LengthMismatch,
    BadCrc,
    OutputTooSmall,
}

/// IEEE/zlib CRC-32 (reflected, init 0xFFFFFFFF, final xor) — matches
/// Python's zlib.crc32.
pub fn crc32(data: &[u8]) -> u32 {
    let mut crc: u32 = 0xFFFF_FFFF;
    for &b in data {
        crc ^= b as u32;
        for _ in 0..8 {
            let mask = (crc & 1).wrapping_neg();
            crc = (crc >> 1) ^ (0xEDB8_8320 & mask);
        }
    }
    !crc
}

fn read_f32(b: &[u8], at: usize) -> f32 {
    f32::from_le_bytes([b[at], b[at + 1], b[at + 2], b[at + 3]])
}

/// Parse a blob into `out`; returns the number of sensors parsed.
pub fn parse_blob(
    blob: &[u8],
    out: &mut [SensorExtrinsic],
) -> Result<usize, ExtrinsicsError> {
    if blob.len() < 12 {
        return Err(ExtrinsicsError::TooShort);
    }
    if blob[0..4] != MAGIC {
        return Err(ExtrinsicsError::BadMagic);
    }
    let version = u16::from_le_bytes([blob[4], blob[5]]);
    if version != VERSION {
        return Err(ExtrinsicsError::BadVersion);
    }
    let count = u16::from_le_bytes([blob[6], blob[7]]) as usize;
    if blob.len() != 8 + 32 * count + 4 {
        return Err(ExtrinsicsError::LengthMismatch);
    }
    let body = &blob[..blob.len() - 4];
    let stored = u32::from_le_bytes([
        blob[blob.len() - 4],
        blob[blob.len() - 3],
        blob[blob.len() - 2],
        blob[blob.len() - 1],
    ]);
    if crc32(body) != stored {
        return Err(ExtrinsicsError::BadCrc);
    }
    if out.len() < count {
        return Err(ExtrinsicsError::OutputTooSmall);
    }
    for (i, slot) in out.iter_mut().take(count).enumerate() {
        let rec = &blob[8 + 32 * i..8 + 32 * (i + 1)];
        *slot = SensorExtrinsic {
            sensor_id: rec[0],
            rotation: Quat::from_array(&[
                read_f32(rec, 4),
                read_f32(rec, 8),
                read_f32(rec, 12),
                read_f32(rec, 16),
            ]),
            offset: Vec3::new(
                read_f32(rec, 20),
                read_f32(rec, 24),
                read_f32(rec, 28),
            ),
        };
    }
    Ok(count)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn golden_blob() -> Vec<u8> {
        // Generated by //swarm/tools:example_extrinsics_blob from
        // examples/widget_v1.json (contract test: Python encodes, Rust
        // parses).
        let path = format!(
            "{}/_main/swarm/tools/examples/widget_v1.wext",
            std::env::var("TEST_SRCDIR").unwrap()
        );
        std::fs::read(path).unwrap()
    }

    #[test]
    fn parses_python_generated_blob() {
        let blob = golden_blob();
        let mut out = [SensorExtrinsic::default(); 16];
        let n = parse_blob(&blob, &mut out).unwrap();
        assert_eq!(n, 5);
        // Sensors are sorted by id: imu, mag, uwb, gps, alt.
        assert_eq!(out[0].sensor_id, SENSOR_IMU);
        assert!((out[0].rotation.w - 1.0).abs() < 1e-6);
        assert!((out[0].offset.x - 0.012).abs() < 1e-6);
        // mag: sensor +x maps to widget +y (90 deg about z).
        let mag = out[1];
        assert_eq!(mag.sensor_id, SENSOR_MAG);
        let mapped = mag.to_widget_dir(Vec3::new(1.0, 0.0, 0.0));
        assert!((mapped.y - 1.0).abs() < 1e-5, "{:?}", mapped);
        // uwb offset survives position mapping.
        let uwb = out[2];
        assert_eq!(uwb.sensor_id, SENSOR_UWB);
        let p = uwb.to_widget_pos(Vec3::ZERO);
        assert!((p.y - 0.021).abs() < 1e-6 && (p.z - 0.008).abs() < 1e-6);
    }

    #[test]
    fn rejects_corruption() {
        let mut blob = golden_blob();
        let mut out = [SensorExtrinsic::default(); 16];
        let last = blob.len() - 6;
        blob[last] ^= 0xFF; // flip a payload byte -> CRC must catch it
        assert_eq!(parse_blob(&blob, &mut out), Err(ExtrinsicsError::BadCrc));
        assert_eq!(
            parse_blob(&blob[..8], &mut out),
            Err(ExtrinsicsError::TooShort)
        );
    }

    #[test]
    fn crc_matches_zlib_vector() {
        // zlib.crc32(b"123456789") == 0xCBF43926 — the standard check value.
        assert_eq!(crc32(b"123456789"), 0xCBF43926);
    }
}
